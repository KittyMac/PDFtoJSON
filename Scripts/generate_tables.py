#!/usr/bin/env python3
"""
Generates Sources/PDFtoJSON/Fonts/FontTables.swift:
- standard single-byte encodings (Standard, WinAnsi, MacRoman, Symbol, ZapfDingbats)
- the Adobe Glyph List (+ TeX glyph names) as compact text, parsed lazily
- advance widths of the standard 14 fonts, keyed by Unicode scalar
Sources: pypdf (encodings, glyph list), reportlab (Adobe AFM widths).
"""
import pypdf._codecs as codecs
from pypdf._codecs.adobe_glyphs import adobe_glyphs
from reportlab.pdfbase import _fontdata

def table(name, chars, cleanup_c1=False):
    vals = []
    for i, ch in enumerate(chars):
        v = ord(ch) if ch else 0
        if v < 0x20 and i >= 0x20: v = 0           # undefined
        if v < 0x20 and i < 0x20 and v == i: v = 0  # control codes are not glyphs
        if cleanup_c1 and 0x80 <= v <= 0x9F and v == i: v = 0
        vals.append(v)
    rows = ["    " + ", ".join("0x%04X" % v for v in vals[r:r+16]) + "," for r in range(0, 256, 16)]
    return "let %s: [UInt16] = [\n%s\n]\n" % (name, "\n".join(rows))

glyphs = {}
for k, v in adobe_glyphs.items():
    if not k.startswith("/") or any(0xD800 <= ord(c) < 0xE000 for c in v):
        continue
    glyphs[k[1:]] = v
agl = "\n".join("%s %s" % (k, " ".join("%04X" % ord(c) for c in v)) for k, v in sorted(glyphs.items()))

widths = []
for font, names in sorted(_fontdata.widthsByFontGlyph.items()):
    entries = {}
    for glyph, w in names.items():
        u = glyphs.get(glyph)
        if font in ("Symbol", "ZapfDingbats") or u is None or len(u) != 1:
            continue
        entries[ord(u)] = w
    widths.append(font + "|" + ",".join("%X:%d" % (u, w) for u, w in sorted(entries.items())))

out = ["// Generated by Scripts/generate_tables.py -- do not edit.", "", "import Foundation", ""]
out.append(table("standardEncoding", codecs._std_encoding))
out.append(table("winAnsiEncoding", codecs._win_encoding, cleanup_c1=True))
out.append(table("macRomanEncoding", codecs._mac_encoding))
out.append(table("symbolEncoding", codecs._symbol_encoding))
out.append(table("zapfDingbatsEncoding", codecs._zapfding_encoding))
out.append('/// "glyphname HEX [HEX]" per line\nlet adobeGlyphListData = """\n%s\n"""\n' % agl)
out.append('/// "FontName|unicodeHex:width,..." per line (widths in 1/1000 em)\nlet standardFontWidthData = """\n%s\n"""\n' % "\n".join(widths))
import os
os.makedirs("Sources/PDFtoJSON/Fonts", exist_ok=True)
open("Sources/PDFtoJSON/Fonts/FontTables.swift", "w").write("\n".join(out))
print("glyphs", len(glyphs), "fonts", len(widths))
